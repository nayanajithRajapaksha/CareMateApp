async function patchTranslations() {
  for (const file of tsFiles) {
    if (!fs.existsSync(file)) continue;
    let content = fs.readFileSync(file, 'utf8');
    const langMatch = file.match(/(en|si|ta)\.ts$/);
    if (!langMatch) continue;
    const lang = langMatch[1];
    const trans = translations[lang];
    if (!trans) continue;
    
    // Convert translations to string
    let newKeys = '';
    for (const [key, value] of Object.entries(trans)) {
      newKeys += `\n  ${key}: ${JSON.stringify(value)},`;
    }
    
    // Replace closing bracket with our new keys and the closing bracket
    content = content.replace(/};\s*$/, newKeys + '\n};\n');
    fs.writeFileSync(file, content, 'utf8');
    console.log('Patched ' + file);
  }
}

